package com.lms.pojo;

public class DashboardStats {
	
	private int totalBooks;
	private int boooksAssigned;
	private int booksReturned;
	private int totalUsers;
	
	public int getTotalBooks() {
		return totalBooks;
	}
	public void setTotalBooks(int totalBooks) {
		this.totalBooks = totalBooks;
	}
	public int getBoooksAssigned() {
		return boooksAssigned;
	}
	public void setBoooksAssigned(int boooksAssigned) {
		this.boooksAssigned = boooksAssigned;
	}
	public int getBooksReturned() {
		return booksReturned;
	}
	public void setBooksReturned(int booksReturned) {
		this.booksReturned = booksReturned;
	}
	public int getTotalUsers() {
		return totalUsers;
	}
	public void setTotalUsers(int totalUsers) {
		this.totalUsers = totalUsers;
	}
	
	
	
	
	
	
}
